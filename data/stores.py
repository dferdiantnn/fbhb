def get_store_name(code: str) -> str | None:
    """Retrieve store name by code (case-insensitive)."""
    return STORE_DB.get(code.strip().upper())

def search_stores(keyword: str) -> dict[str, str]:
    """Search stores by keyword in code or name."""
    kw = keyword.strip().upper()
    return {k: v for k, v in STORE_DB.items() if kw in k.upper() or kw in v.upper()}

def get_region_stores(region_id: str) -> dict[str, str]:
    """Retrieve all stores within a specific region ID."""
    reg = STORE_REGIONS.get(str(region_id))
    return reg["stores"] if reg else {}

def get_all_regions() -> dict:
    """Return all available regions metadata."""
    return {k: v["name"] for k, v in STORE_REGIONS.items()}

def get_all_stores_count() -> int:
    """Return total registered stores count."""
    return len(STORE_DB)
